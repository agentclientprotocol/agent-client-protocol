#!/usr/bin/env python3
"""Check that draft protocol pages only differ from their stable copies where expected.

Each `docs/protocol/vN/draft/<page>.mdx` is a copy of `docs/protocol/vN/<page>.mdx`
plus unstable features. Both are maintained by hand, so this script compares them
after normalizing differences that don't matter (draft link prefixes, line wrapping,
table padding) and checks the remaining differences against a committed baseline in
`scripts/draft-differences/`.

When a stable page changes, apply the same change to its draft copy (or vice versa).
If the difference is intended, such as new draft-only content, update the baseline:

    python3 scripts/check_draft_docs.py --update
"""

import argparse
import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROTOCOL = ROOT / "docs" / "protocol"
BASELINE = ROOT / "scripts" / "draft-differences"
VERSIONS = ("v1", "v2")
SKIP = {"schema.mdx"}  # Generated by the schema generator.


def normalize(text: str, version: str) -> list[str]:
    """Return the page as a list of comparable blocks."""
    text = text.replace(f"/protocol/{version}/draft/", f"/protocol/{version}/")
    blocks: list[str] = []
    paragraph: list[str] = []
    fence: list[str] | None = None

    def flush() -> None:
        if paragraph:
            joined = re.sub(r"\s+", " ", " ".join(line.strip() for line in paragraph))
            # Ignore JSX formatting that depends on line length.
            joined = re.sub(r"\[\s*", "[", joined)
            joined = re.sub(r",?\s*\]", "]", joined)
            joined = re.sub(r"\s+>", ">", joined)
            blocks.append(joined.strip())
            paragraph.clear()

    for line in text.splitlines():
        if fence is not None:
            fence.append(line.rstrip())
            if line.lstrip().startswith("```"):
                blocks.append("\n".join(fence))
                fence = None
            continue
        if line.lstrip().startswith("```"):
            flush()
            fence = [line.rstrip()]
        elif line.lstrip().startswith("|"):
            flush()
            row = re.sub(r"\s*\|\s*", "|", line.strip())
            blocks.append(re.sub(r"-{3,}", "---", row))
        elif not line.strip():
            flush()
        elif re.match(r"\s*([-*]|\d+\.)\s", line) or (
            line.lstrip().startswith(("#", "<"))
            and "".join(paragraph).count("[") == "".join(paragraph).count("]")
        ):
            flush()
            paragraph.append(line)
        else:
            paragraph.append(line)
    flush()
    if fence is not None:
        blocks.append("\n".join(fence))
    return blocks


def page_diff(version: str, page: str) -> str:
    stable = PROTOCOL / version / page
    draft = PROTOCOL / version / "draft" / page
    lines = difflib.unified_diff(
        normalize(stable.read_text(), version),
        normalize(draft.read_text(), version),
        fromfile=f"{version}/{page}",
        tofile=f"{version}/draft/{page}",
        n=1,
        lineterm="",
    )
    return "\n".join(lines) + "\n"


def pairs():
    for version in VERSIONS:
        for draft in sorted((PROTOCOL / version / "draft").glob("*.mdx")):
            if draft.name not in SKIP and (PROTOCOL / version / draft.name).exists():
                yield version, draft.name


def baseline_path(version: str, page: str) -> Path:
    return BASELINE / f"{version}-{Path(page).stem}.diff"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--update", action="store_true", help="rewrite the baseline")
    args = parser.parse_args()

    expected_files = set()
    failures = []
    for version, page in pairs():
        diff = page_diff(version, page)
        path = baseline_path(version, page)
        if diff.strip() == "":
            diff = ""
        if diff:
            expected_files.add(path)
        if args.update:
            if diff:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(diff)
            elif path.exists():
                path.unlink()
        elif (path.read_text() if path.exists() else "") != diff:
            failures.append(f"{version}/{page} and {version}/draft/{page}")

    if args.update:
        for stale in BASELINE.glob("*.diff"):
            if stale not in expected_files:
                stale.unlink()
        return 0

    stale = [p.name for p in BASELINE.glob("*.diff") if p not in expected_files]
    if failures or stale:
        for failure in failures:
            print(f"Stable and draft pages differ from the baseline: {failure}")
        for name in stale:
            print(f"Stale baseline file: {name}")
        print(
            "\nApply the change to both copies, or if the difference is intended, run:\n"
            "  python3 scripts/check_draft_docs.py --update",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
